print(a.startswith("python")) #it is used to check if the string starts with a specific substring
print(a.endswith("language")) #it is used to check if the string ends with a specific substring
print(a.upper()) #it is used to convert the string to uppercase
print(a.lower()) #it is used to convert the string to lowercase
print(a.split()) #it is used to split the string into a list of words####
